'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { before, after, beforeEach } = test;
const C = require('../../js/core.js');
const { fixture } = require('./helpers');
const { ValidationError } = require('../../server/db/errors');
const policy = require('../../server/services/input-policy');

const MB = 1024 * 1024;
const base64Of = (bytes) => Buffer.alloc(bytes, 7).toString('base64');
const file = (name, type, data = `data:${type};base64,${base64Of(16)}`) => ({
  id: C.uid('file'),
  name,
  type,
  size: 16,
  data,
});

let f, client;
before(async () => {
  f = await fixture();
  client = f.client();
  assert.equal((await client.login()).status, 200);
});
after(async () => {
  await f.cleanup();
});
beforeEach(() => {
  for (const name of ['company', 'customers', 'products', 'orders', 'packingLists'])
    f.repositories[name].clear();
  f.sequenceService.clear();
});

async function post(path, body) {
  const token = (await (await client.request('/api/auth/csrf')).json()).csrfToken;
  return client.request(path, {
    method: 'POST',
    headers: { Origin: f.config.origin, 'X-CSRF-Token': token, 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
}
function seedCustomer(id = 'customer-test') {
  if (!f.repositories.customers.get(id))
    f.repositories.customers.put({ id, buyerName: 'TEST Buyer' }, 0);
  return id;
}
function createOrder(extra = {}) {
  return f.businessCrudService.create('orders', {
    id: C.uid('order'),
    customerId: seedCustomer(),
    currency: 'USD',
    items: [{ id: 'line-1', description: 'TEST item', quantity: 1, unitPrice: 10 }],
    ...extra,
  });
}

test('record ids generated by the application and sample data are accepted', () => {
  for (const id of [
    C.uid('customer'),
    C.uid('order'),
    'customer-northstar',
    'main',
    'c1',
    'a.b:c_d-1',
  ])
    assert.equal(policy.requireNewRecordId(id), id);
});

test('new record ids with markup, spaces or excessive length are rejected', () => {
  for (const id of ['x"><b>', 'has space', '', '-leading', 'a'.repeat(129), 'é', null, 42])
    assert.throws(() => policy.requireNewRecordId(id), ValidationError);
});

test('creating a customer, product or order with an unsafe id is rejected over HTTP', async () => {
  const response = await post('/api/customers', {
    id: 'x"><meta http-equiv=refresh>',
    buyerName: 'X',
  });
  assert.equal(response.status, 400);
  assert.match((await response.json()).error, /Record id/);
  assert.equal(f.repositories.customers.list().length, 0);
  assert.throws(() => f.businessCrudService.create('products', { id: 'p "1"' }), ValidationError);
});

test('bulk product import validates only new ids and keeps legacy ids updatable', () => {
  f.repositories.products.put({ id: 'legacy product id', englishName: 'Old' }, 0);
  const rows = f.businessCrudService.bulkPutProducts([
    { data: { id: 'legacy product id', englishName: 'Updated' }, expectedVersion: 1 },
    { data: { id: C.uid('product'), englishName: 'New' }, expectedVersion: 0 },
  ]);
  assert.equal(rows[0].payload.englishName, 'Updated');
  assert.throws(
    () => f.businessCrudService.bulkPutProducts([{ data: { id: '<p>' }, expectedVersion: 0 }]),
    ValidationError,
  );
});

test('order currency must be a three-letter code but legacy values stay editable', () => {
  assert.equal(createOrder({ currency: 'CNY' }).payload.currency, 'CNY');
  assert.equal(createOrder({ currency: 'RMB' }).payload.currency, 'RMB');
  for (const currency of ['usd', 'US', '<b>USD</b>', 'US D'])
    assert.throws(() => createOrder({ currency }), ValidationError);

  const legacy = {
    id: 'order-legacy',
    customerId: seedCustomer('customer-legacy'),
    currency: 'usd',
  };
  f.repositories.orders.put(legacy, 0);
  f.repositories.orders.setMetadata(legacy.id, {
    owner_user_id: f.user?.id ?? null,
    customer_id: legacy.customerId,
  });
  const updated = f.orderOperationService.updateOrder(legacy.id, { ...legacy, notes: 'edited' }, 1);
  assert.equal(updated.payload.currency, 'usd');
  assert.throws(
    () =>
      f.orderOperationService.updateOrder(legacy.id, { ...updated.payload, currency: '"><b>' }, 2),
    ValidationError,
  );
});

test('ordinary business attachments are accepted', () => {
  const order = createOrder({
    attachments: [
      file('Commercial Invoice.pdf', 'application/pdf'),
      file('packing photo.jpg', 'image/jpeg'),
      file('price list.xlsx', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'),
      file('notes.txt', 'text/plain'),
      file('empty.bin', 'application/octet-stream', 'data:'),
    ],
  });
  assert.equal(order.payload.attachments.length, 5);
});

test('active web content attachments are rejected by declared type, data type or extension', () => {
  for (const attachment of [
    file('page.html', 'text/html'),
    file('logo.svg', 'image/svg+xml'),
    file('script.js', 'application/javascript'),
    file('innocent.pdf', 'application/pdf', `data:text/html;base64,${base64Of(8)}`),
    file('renamed.HTM', 'application/octet-stream'),
  ])
    assert.throws(() => createOrder({ attachments: [attachment] }), /HTML, SVG and script/);
});

test('malformed or oversized attachment data is rejected', () => {
  for (const data of ['https://example.invalid/x.pdf', 'data:text/plain,raw', 'data:;base64,@@@@'])
    assert.throws(
      () => createOrder({ attachments: [file('x.txt', 'text/plain', data)] }),
      ValidationError,
    );
  assert.throws(() => createOrder({ attachments: [file('a/b.txt', 'text/plain')] }), /file name/);
  const big = file(
    'big.pdf',
    'application/pdf',
    `data:application/pdf;base64,${base64Of(20 * MB + 3)}`,
  );
  assert.throws(() => createOrder({ attachments: [big] }), /20 MB/);
  const limit = file(
    'limit.pdf',
    'application/pdf',
    `data:application/pdf;base64,${base64Of(20 * MB)}`,
  );
  assert.equal(createOrder({ attachments: [limit] }).payload.attachments.length, 1);
});

test('historical attachments are kept while new ones on the same order are validated', () => {
  const legacyFile = file('legacy.html', 'text/html');
  const legacy = {
    id: 'order-with-legacy-file',
    customerId: seedCustomer('customer-files'),
    currency: 'USD',
    attachments: [legacyFile],
  };
  f.repositories.orders.put(legacy, 0);
  const kept = f.orderOperationService.updateOrder(legacy.id, { ...legacy, notes: 'edited' }, 1);
  assert.equal(kept.payload.attachments[0].name, 'legacy.html');
  assert.throws(
    () =>
      f.orderOperationService.updateOrder(
        legacy.id,
        { ...kept.payload, attachments: [legacyFile, file('new.svg', 'image/svg+xml')] },
        2,
      ),
    ValidationError,
  );
});

test('payment tracking validates new payment slips and payment currencies', () => {
  const order = createOrder();
  const payment = (slip, currency = 'USD') => ({
    paymentRecords: [
      { id: 'payment-1', amount: 5, status: 'Pending', currency, paymentSlip: slip },
    ],
    currentPaymentStage: C.PAYMENT_STAGES[0].value,
  });
  const ok = f.orderOperationService.action(
    'payment-tracking',
    order.payload.id,
    payment(file('slip.png', 'image/png')),
    1,
  );
  assert.equal(ok.payload.paymentRecords[0].paymentSlip.name, 'slip.png');
  assert.throws(
    () =>
      f.orderOperationService.action(
        'payment-tracking',
        order.payload.id,
        payment(file('slip.html', 'text/html')),
        2,
      ),
    /HTML, SVG and script/,
  );
  assert.throws(
    () =>
      f.orderOperationService.action('payment-tracking', order.payload.id, payment(null, '<i>'), 2),
    /Payment currency/,
  );
});

test('browser and server share one attachment policy', () => {
  assert.equal(C.attachmentProblem({ name: 'invoice.pdf', type: 'application/pdf', size: 1 }), '');
  assert.match(C.attachmentProblem({ name: 'x.svg', type: '', size: 1 }), /SVG/);
  assert.match(
    C.attachmentProblem({
      name: 'x.pdf',
      type: 'application/pdf',
      size: C.ATTACHMENT_MAX_BYTES + 1,
    }),
    /20 MB/,
  );
  assert.deepEqual(policy.dataUrlInfo(`data:application/pdf;base64,${base64Of(10)}`), {
    type: 'application/pdf',
    bytes: 10,
  });
});
